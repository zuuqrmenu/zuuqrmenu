/**
 * Normalizes Turkish and international characters, removes excess spacing and symbols
 */
export const normalizeCategoryText = (text = '') => {
  if (!text || typeof text !== 'string') return '';
  return text
    .toLocaleLowerCase('tr-TR')
    .replace(/ç/g, 'c')
    .replace(/ğ/g, 'g')
    .replace(/ı/g, 'i')
    .replace(/i̇/g, 'i')
    .replace(/ö/g, 'o')
    .replace(/ş/g, 's')
    .replace(/ü/g, 'u')
    .replace(/[^\w\s&]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
};

/**
 * Matches user input to one of the recognized categories
 * @param {string} input - User typed string
 * @returns {object|null} - Matching category template or null
 */
export const findMatchingCategory = (input = '') => {
  const normalized = normalizeCategoryText(input);
  if (!normalized) return null;

  for (const item of Object.values(CATEGORY_DESCRIPTION_TEMPLATES)) {
    // 1. Exact match on normalized canonical name
    if (normalizeCategoryText(item.name) === normalized) {
      return item;
    }

    // 2. Exact match on normalized alias
    for (const alias of item.aliases) {
      if (normalizeCategoryText(alias) === normalized) {
        return item;
      }
    }
  }

  // 3. Prefix/inclusion match if user typed partial words (at least 3 chars)
  if (normalized.length >= 3) {
    for (const item of Object.values(CATEGORY_DESCRIPTION_TEMPLATES)) {
      const normName = normalizeCategoryText(item.name);
      if (normName.startsWith(normalized) || normalized.startsWith(normName)) {
        return item;
      }
      for (const alias of item.aliases) {
        const normAlias = normalizeCategoryText(alias);
        if (normAlias === normalized || (normAlias.length >= 4 && (normAlias.startsWith(normalized) || normalized.startsWith(normAlias)))) {
          return item;
        }
      }
    }
  }

  return null;
};

/**
 * Returns filtered list of recommended categories based on input text
 */
export const getFilteredCategorySuggestions = (input = '') => {
  const allList = Object.values(CATEGORY_DESCRIPTION_TEMPLATES).map((c) => ({
    key: c.key,
    name: c.name,
  }));

  const normalized = normalizeCategoryText(input);
  if (!normalized) return allList;

  return allList.filter((cat) => {
    const item = CATEGORY_DESCRIPTION_TEMPLATES[cat.key];
    const normName = normalizeCategoryText(item.name);
    if (normName.includes(normalized)) return true;
    return item.aliases.some((a) => normalizeCategoryText(a).includes(normalized));
  });
};

/**
 * In-memory session counter state per category
 * Preserved during the user's session while the dashboard page is open.
 * Example: { starters: 3, soups: 1, desserts: 0 }
 */
const categoryCounterMap = {};

/**
 * Returns how many template descriptions have been used for a category
 */
export const getCategoryTemplateCounter = (categoryKey) => {
  if (!categoryKey) return 0;
  return categoryCounterMap[categoryKey] || 0;
};

/**
 * Checks if a category still has unused description templates (< 10)
 */
export const hasRemainingCategoryDescriptions = (categoryKey) => {
  const item = CATEGORY_DESCRIPTION_TEMPLATES[categoryKey];
  if (!item || !item.descriptions) return false;
  const current = categoryCounterMap[categoryKey] || 0;
  return current < item.descriptions.length;
};

/**
 * Sequential cycling template retrieval
 * Returns descriptions in order (1 to 10), and once finished, loops back
 * to the beginning in the exact same sequence continuously.
 * Absolutely NO AI API calls.
 */
export const getNextCategoryDescription = (categoryKey) => {
  const item = CATEGORY_DESCRIPTION_TEMPLATES[categoryKey];
  if (!item || !item.descriptions || item.descriptions.length === 0) {
    return null;
  }

  const currentCount = categoryCounterMap[categoryKey] || 0;
  const total = item.descriptions.length;
  const index = currentCount % total;

  const description = item.descriptions[index];
  const nextCount = currentCount + 1;
  categoryCounterMap[categoryKey] = nextCount;

  return {
    description,
    counter: nextCount,
    index,
    total,
    isExhausted: false,
  };
};

/**
 * Resets counters (useful for testing or manual session resets)
 */
export const resetCategoryTemplateCounters = (categoryKey = null) => {
  if (categoryKey) {
    delete categoryCounterMap[categoryKey];
  } else {
    Object.keys(categoryCounterMap).forEach((k) => delete categoryCounterMap[k]);
  }
};

